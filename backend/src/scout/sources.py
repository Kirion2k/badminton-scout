# Serving from our database always means we stored the records. A deployment also shows them
# to people other than the developer.
_SERVE_REQUIRES: Mapping[Environment, frozenset[Use]] = MappingProxyType(
    {
        "development": frozenset({Use.LOCAL_RESEARCH, Use.STORE}),
        "test": frozenset({Use.LOCAL_RESEARCH, Use.STORE}),
        "production": frozenset({Use.STORE, Use.REDISTRIBUTE, Use.HOSTED}),
    }
)


class SourceNotPermitted(Exception):
    pass


def is_permitted(source_id: str, use: Use) -> bool:
    rights = SOURCES.get(source_id)
    return rights is not None and use in rights.grants


def can_serve(source_id: str, env: Environment) -> bool:
    required = _SERVE_REQUIRES.get(env)
    if required is None:  # an environment nobody assessed is denied, not defaulted
        return False
    return all(is_permitted(source_id, use) for use in required)


def require_permitted(source_id: str, use: Use) -> None:
    if not is_permitted(source_id, use):
        raise SourceNotPermitted(f"source {source_id!r} has no {use.value!r} grant")
